import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash,generateKeyPairSync} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {execFile,execFileSync} from 'node:child_process';
import {promisify} from 'node:util';
if(process.platform!=='linux'||process.env.GITHUB_ACTIONS!=='true') throw new Error('Browser runs are restricted to GitHub Linux runners');
const here=path.dirname(fileURLToPath(import.meta.url));
const work=path.resolve(here,'../../../.work/17-chrome');
const out=path.join(work,'artifacts'); fs.mkdirSync(out,{recursive:true});
const {fixtures}=await import('./fixture.mjs');
const {launch,address,key,delay,activateChrome,screenshot,stopChrome}=await import('./ui.mjs');
const {nativeBridge,evaluate,eventually}=await import('./protocol.mjs');
const {save,readAndAct,holdChecks,publicChecks,disconnectProbe,auditDeliveries}=await import('./checks.mjs');
const {pack,installExternal}=await import('./install.mjs');
const fixture=await fixtures(out);
const profile=path.join(work,'profile');
const manifest=JSON.parse(fs.readFileSync(path.join(here,'extension/manifest.json')));
const extDir=path.join(work,'own-extension');fs.cpSync(path.join(here,'extension'),extDir,{recursive:true});
const keypair=generateKeyPairSync('rsa',{modulusLength:2048});
manifest.key=keypair.publicKey.export({type:'spki',format:'der'}).toString('base64');
fs.writeFileSync(path.join(extDir,'manifest.json'),JSON.stringify(manifest));
const id=[...createHash('sha256').update(Buffer.from(manifest.key,'base64')).digest().subarray(0,16)].map(b=>String.fromCharCode(97+(b>>4),97+(b&15))).join('');
const socketPath=path.join(work,'native.sock');
process.env.CHROME_CHECK_SOCKET=socketPath;
const host={name:'org.aresos.chrome_check',description:'CI feasibility check',path:path.join(here,'native-host.py'),type:'stdio',allowed_origins:[`chrome-extension://${id}/`]};
for(const dir of [path.join(profile,'NativeMessagingHosts'),path.join(process.env.XDG_CONFIG_HOME,'google-chrome/NativeMessagingHosts')]){fs.mkdirSync(dir,{recursive:true});fs.writeFileSync(path.join(dir,host.name+'.json'),JSON.stringify(host));}
let chrome,bridge;
const summary={run:process.env.GITHUB_RUN_ID,attempt:process.env.GITHUB_RUN_ATTEMPT,head:process.env.GITHUB_SHA};
try {
  chrome=launch(profile,fixture.base+'/login',path.join(out,'chrome-initial.log'),[`--load-extension=${extDir}`]);
  await activateChrome();
  await eventually(()=>fixture.arrivals.some(a=>a.kind==='login-ready'),'fixture login has keyboard focus');
  await key('Return');
  await eventually(()=>fixture.arrivals.some(a=>a.kind==='owner-page'&&a.signedIn),'fixture signed-in page');
  console.log('LOGIN_BEFORE_TOOL',JSON.stringify(fixture.arrivals));
  await screenshot(out,'signed-in-before-tool');
  await address(`chrome-extension://${id}/select.html`);await screenshot(out,'load-extension-flag-probe');
  await stopChrome(chrome);
  const crx=pack(extDir,work,keypair);installExternal(id,manifest.version,crx,work);
  // Installed extension and cookie survive a normal restart. No attach tool is running yet.
  chrome=launch(profile,fixture.base+'/owner',path.join(out,'chrome-normal.log'));await activateChrome();await delay(1500);
  assert.ok(fixture.arrivals.at(-1).signedIn);
  summary.toolStartedAt=Date.now();bridge=await nativeBridge(socketPath);
  const spoofed=new Promise(r=>bridge.once('check.connected',r));
  await promisify(execFile)(process.execPath,[path.join(here,'peer-probe.mjs'),'native',socketPath],{timeout:5000});
  summary.nativePeer=await spoofed;assert.equal(summary.nativePeer.tabId,-1);
  console.log('NATIVE_SAME_UID_PEER',JSON.stringify(summary.nativePeer),'untrusted peer can impersonate host before owner selection; not authenticated');
  await delay(200);
  const connected=new Promise(r=>bridge.once('check.connected',r));
  await key('ctrl+t');await address(`chrome-extension://${id}/select.html?url=${encodeURIComponent(fixture.base+'/owner')}`);
  await screenshot(out,'select-tab');await key('Return');
  summary.native=await Promise.race([connected,delay(5000).then(()=>{throw Error('Native host did not connect');})]);
  await screenshot(out,'native-attached');
  assert.match(await evaluate(bridge,'document.body.innerText'),/Signed in: synthetic member/);
  console.log('ATTACH_NATIVE PASS',JSON.stringify(summary.native),'cookie persisted; tab preceded tool; normal restart');
  const processes=execFileSync('ps',['-C','chrome','-o','pid,args'],{encoding:'utf8'});
  const listeners=execFileSync('ss',['-lntp'],{encoding:'utf8'}).split('\n').filter(line=>line.includes('"chrome"'));
  assert.doesNotMatch(processes,/--no-sandbox|--remote-debugging-(port|pipe)/);assert.equal(listeners.length,0);
  const socketMode=fs.statSync(socketPath).mode&0o777;assert.equal(socketMode,0o600);
  save(out,'native-transport',{processes,listeners,socketMode});console.log('NATIVE_NO_DEBUG_TCP PASS');
  summary.metrics=await readAndAct(bridge,fixture,out,'native');
  summary.holds=await holdChecks(bridge,fixture,out,'native');
  await key('ctrl+t');await address('chrome://sandbox');await screenshot(out,'sandbox-status');
  summary.disconnect=await disconnectProbe(bridge,fixture,out,'native',async()=>bridge.close());bridge=undefined;
  await stopChrome(chrome);chrome=undefined;
  const {otherRoutes}=await import('./routes.mjs');
  summary.routes=await otherRoutes({here,work,out,profile,fixture});
  summary.public=summary.routes.playwright.public;
  auditDeliveries(fixture,out,[summary.holds,summary.routes.playwright.holds,summary.routes.consent.holds]);
  if(summary.routes.publicFailure)throw Error(summary.routes.publicFailure);
  assert.equal(fixture.arrivals.filter(r=>r.url?.includes('other-tab-mutated')).length,0);
  console.log('ALL CHECKS COMPLETE');
} catch(error){
  await screenshot(out,'failure');throw error;
} finally {
  save(out,'summary',summary);
  if(chrome)await stopChrome(chrome);
  bridge?.close();fixture.close();
}
