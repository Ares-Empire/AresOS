import importlib.util
import pathlib
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('artifact_class', ROOT/'reviews/14-owner-tools/classify-artifacts.py')
classifier = importlib.util.module_from_spec(spec)
spec.loader.exec_module(classifier)


class ArtifactClassTest(unittest.TestCase):
    def test_both_public_certificate_names_and_exact_forty_hex(self):
        for label in ('Fedora kernel signing key', 'Build time autogenerated kernel key'):
            line = "[    0.123456] Loaded X.509 cert '"+label+': '+('aB09'*10)+"'"
            proof = classifier.kernel_line(line)
            self.assertEqual(proof['certificate_label'], label)
            self.assertEqual(proof['fingerprint_hex_length'], 40)

    def test_prefix_suffix_wrong_message_length_control_or_nonhex_refuses(self):
        good = "[    0.123456] Loaded X.509 cert 'Build time autogenerated kernel key: "+'a'*40+"'"
        bad = [good+' extra', 'echo '+good, good.replace('Loaded X.509 cert', 'API token'),
               good.replace('a'*40, 'a'*39), good.replace('a'*40, 'a'*41),
               good.replace('a'*40, 'g'*40), good+'\nother', '\x1b[0m'+good,
               '\v'+good, good.replace('Build time autogenerated kernel key', '')]
        for line in bad:
            with self.subTest(line=line), self.assertRaisesRegex(AssertionError, 'STOP:'):
                classifier.kernel_line(line)


if __name__ == '__main__': unittest.main()
