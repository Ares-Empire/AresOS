#!/usr/bin/env python3
"""Write a labwc theme folder from a look pack (needs Pillow)."""
import argparse
import json
from pathlib import Path

from PIL import Image


BUTTON_SIZE = (48, 40)


def themerc(colours):
    active = colours['active']
    inactive = colours['inactive']
    menu = colours['menu']
    switcher = colours['switcher']
    snap = colours['snap']
    outline = ','.join(switcher['outline'])
    snap_lines = ','.join(snap['lines'])
    return f'''# Generated by os/look/make_labwc_theme.py from a look pack.
# Regenerate this folder after changing the pack's frame.
border.width: 2
window.active.border.color: {active['border']}
window.inactive.border.color: {inactive['border']}
window.titlebar.padding.width: 0
window.titlebar.padding.height: 0
window.active.title.bg: Solid
window.active.title.bg.color: {active['bar']}
window.inactive.title.bg: Solid
window.inactive.title.bg.color: {inactive['bar']}
window.active.label.text.color: {active['title']}
window.inactive.label.text.color: {inactive['title']}
window.label.text.justify: Left
window.button.width: {BUTTON_SIZE[0]}
window.button.height: {BUTTON_SIZE[1]}
window.button.spacing: 0
window.active.shadow.size: 24
window.active.shadow.color: {active['shadow']}
window.inactive.shadow.size: 12
window.inactive.shadow.color: {inactive['shadow']}
menu.border.width: 2
menu.border.color: {menu['border']}
menu.items.padding.x: 8
menu.items.padding.y: 0
menu.items.bg.color: {menu['bg']}
menu.items.text.color: {menu['text']}
menu.items.active.bg.color: {menu['chosen_bg']}
menu.items.active.text.color: {menu['chosen_text']}
menu.separator.width: 2
menu.separator.padding.width: 8
menu.separator.padding.height: 4
menu.separator.color: {menu['separator']}
menu.width.min: 200
menu.width.max: 400
osd.bg.color: {switcher['bg']}
osd.border.color: {switcher['border']}
osd.border.width: 2
osd.label.text.color: {switcher['text']}
osd.window-switcher.style-thumbnail.width.max: 80%
osd.window-switcher.style-thumbnail.padding: 8
osd.window-switcher.style-thumbnail.item.width: 280
osd.window-switcher.style-thumbnail.item.height: 208
osd.window-switcher.style-thumbnail.item.padding: 8
osd.window-switcher.style-thumbnail.item.active.border.width: 4
osd.window-switcher.style-thumbnail.item.active.border.color: {switcher['chosen_border']}
osd.window-switcher.style-thumbnail.item.active.bg.color: {switcher['chosen_bg']}
osd.window-switcher.style-thumbnail.item.icon.size: 32
osd.window-switcher.preview.border.width: 2
osd.window-switcher.preview.border.color: {outline}
snapping.overlay.region.bg.enabled: yes
snapping.overlay.edge.bg.enabled: yes
snapping.overlay.region.border.enabled: yes
snapping.overlay.edge.border.enabled: yes
snapping.overlay.region.bg.color: {snap['fill']}
snapping.overlay.edge.bg.color: {snap['fill']}
snapping.overlay.region.border.width: 2
snapping.overlay.edge.border.width: 2
snapping.overlay.region.border.color: {snap_lines}
snapping.overlay.edge.border.color: {snap_lines}
'''


def generate(pack, output):
    manifest = json.loads((pack / 'look.json').read_text(encoding='utf-8'))
    output.mkdir(parents=True, exist_ok=True)
    for name, file in manifest['frame_sprites'].items():
        with Image.open(pack / file) as cell:
            sprite = cell.convert('RGBA').resize(BUTTON_SIZE, Image.Resampling.NEAREST)
            sprite.save(output / name)
    (output / 'themerc').write_text(themerc(manifest['frame_colours']), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pack', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate(args.pack, args.output)
